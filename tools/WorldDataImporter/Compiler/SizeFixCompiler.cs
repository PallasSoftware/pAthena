using System.Globalization;
using System.Text;
namespace Athena.WorldCompiler.Generation;

// Weapon-vs-size damage table (rAthena SizeFixDatabase, status.cpp:492-584). The pinned loader reads db/size_fix.yml
// and then its Footer `Imports` in order, skipping entries whose Mode is not the build mode (Renewal here); a later
// file overrides only the sizes it names for a weapon it repeats, a new weapon defaults unnamed sizes to 100, and a
// value above 100 is clamped to 100. A missing import file is only tolerated for the optional db/import overlay.
internal static class SizeFixCompiler
{
    private static readonly string[] WeaponNames =
    [
        "Fist", "Dagger", "1hSword", "2hSword", "1hSpear", "2hSpear", "1hAxe", "2hAxe", "Mace", "2hMace", "Staff", "Bow", "Knuckle",
        "Musical", "Whip", "Book", "Katar", "Revolver", "Rifle", "Gatling", "Shotgun", "Grenade", "Huuma", "2hStaff",
    ];

    // Pinned weapon_type numeric order (pc.hpp:959), identical to WeaponType's values.
    internal static int[,] BuildTable(Func<string, string?> readFile, string basePath = "db/size_fix.yml", string mode = "Renewal")
    {
        var table = new Dictionary<int, int[]>();
        var baseYaml = readFile(basePath) ?? throw new ArgumentException($"Required pinned source file is missing: {basePath}.");
        // The pinned Footer lists `- Path:` items at the SAME indent as `Imports:` (valid YAML) which SimpleYaml does not
        // accept, so the Footer is read separately from the Body document.
        var footerStart = baseYaml.IndexOf("\nFooter:", StringComparison.Ordinal);
        Apply(SimpleYaml.Parse(footerStart < 0 ? baseYaml : baseYaml[..footerStart], basePath), basePath, table);
        var imports = footerStart < 0 ? [] : ReadImports(baseYaml[footerStart..], basePath);
        foreach (var (path, importMode) in imports)
        {
            if (importMode is not null && importMode != mode) continue;
            var yaml = readFile(path);
            if (yaml is null)
            {
                if (path.StartsWith("db/import/", StringComparison.Ordinal)) continue; // optional operator overlay
                throw new ArgumentException($"Imported pinned source file is missing: {path}.");
            }
            Apply(SimpleYaml.Parse(yaml, path), path, table);
        }

        var result = new int[WeaponNames.Length, 3];
        for (var weapon = 0; weapon < WeaponNames.Length; weapon++)
        {
            // atkmods is only written for weapons present in the database (status.cpp:4226-4230); every pinned
            // weapon has a base entry, so an absent one is a source change this compiler must not paper over.
            if (!table.TryGetValue(weapon, out var sizes)) throw new ArgumentException($"Size fix table has no entry for weapon {WeaponNames[weapon]}.");
            for (var size = 0; size < 3; size++) result[weapon, size] = sizes[size];
        }
        return result;
    }

    private static List<(string Path, string? Mode)> ReadImports(string footer, string sourceName)
    {
        var result = new List<(string, string?)>();
        foreach (var line in footer.Split('\n').Skip(1).Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith('#')))
        {
            if (line is "Footer:" or "Imports:") continue;
            if (line.StartsWith("- Path:", StringComparison.Ordinal)) result.Add((line["- Path:".Length..].Trim(), null));
            else if (line.StartsWith("Mode:", StringComparison.Ordinal) && result.Count > 0) result[^1] = (result[^1].Item1, line["Mode:".Length..].Trim());
            else throw new ArgumentException($"{sourceName}: unrecognized Footer line '{line}'.");
        }
        return result;
    }

    private static void Apply(SimpleYamlMap root, string sourceName, Dictionary<int, int[]> table)
    {
        foreach (var (node, index) in root.Required("Body", sourceName).Sequence($"{sourceName} Body").Items.Select((n, i) => (n, i)))
        {
            var entry = node.Map($"{sourceName} Body[{index}]");
            var name = entry.Required("Weapon", $"{sourceName} Body[{index}]").Scalar("Weapon");
            var weapon = Array.IndexOf(WeaponNames, name);
            if (weapon < 0) throw new ArgumentException($"{sourceName}: unknown size fix weapon '{name}'.");
            var exists = table.TryGetValue(weapon, out var sizes);
            sizes ??= [100, 100, 100];
            foreach (var (key, slot) in new[] { ("Small", 0), ("Medium", 1), ("Large", 2) })
                if (entry.Optional(key) is { } value) sizes[slot] = Math.Min((int)value.UShort($"{sourceName} {name}.{key}"), 100);
            if (!exists) table[weapon] = sizes;
        }
    }

    internal static string Generate(int[,] table, string commit)
    {
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated>")
            .AppendLine("// Generated by Athena.WorldCompiler.")
            .AppendLine("// Source: legacy/rathena/db/size_fix.yml + Footer imports (Renewal)")
            .Append("// rAthena commit: ").AppendLine(commit)
            .AppendLine("// Do not edit this file directly.")
            .AppendLine("// </auto-generated>")
            .AppendLine("using Athena.Net.MapServer.World;")
            .AppendLine()
            .AppendLine("namespace Athena.Net.MapServer.Generated.GameData.SizeFix;")
            .AppendLine()
            .AppendLine("internal static class GeneratedSizeFix")
            .AppendLine("{")
            .AppendLine("    // [WeaponType, MobSize(Small, Medium, Big)] percent, pinned s_sizefix_db small/medium/large.")
            .AppendLine("    private static readonly int[,] Table =")
            .AppendLine("    {");
        for (var weapon = 0; weapon < table.GetLength(0); weapon++)
            builder.Append("        { ").Append(string.Join(", ", Enumerable.Range(0, 3).Select(size => table[weapon, size].ToString(CultureInfo.InvariantCulture)))).Append(" }, // ").Append((WeaponType)weapon).AppendLine();
        builder
            .AppendLine("    };")
            .AppendLine()
            .AppendLine("    internal static int Percent(WeaponType weapon, MobSize size) => Table[(int)weapon, (int)size];")
            .AppendLine("}");
        return builder.ToString();
    }
}
