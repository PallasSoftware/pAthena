using System.Text;
using Athena.Net.MapServer.World.Items;

namespace Athena.WorldCompiler.Generation;

// Builds the item data pack from the pinned rAthena databases: the ported item loader, every item script lowered once per distinct
// source, and a coverage report that names every script that is not fully lowered together with its blocker and owner.
internal static class ItemPackBuilder
{
    internal sealed record BuildResult(ItemPack Pack, string Report);

    internal static BuildResult Build(Func<string, string> readFile, RathenaConstantTable constants, string commit)
    {
        var loaded = ItemDatabaseLoader.Load(readFile, constants);
        var lowerer = new ItemScriptLowerer(constants, RathenaBuiltins.Names(readFile("src/map/script.cpp")));

        var scripts = new List<PackScript>();
        var indexBySource = new Dictionary<string, int>(StringComparer.Ordinal);
        int Index(string? source, string file)
        {
            if (source is null) return -1;
            if (!indexBySource.TryGetValue(source, out var index))
            {
                index = scripts.Count;
                scripts.Add(lowerer.Lower(source, file));
                indexBySource.Add(source, index);
            }
            return index;
        }

        var items = loaded.Items
            .Select(item => item.Item with
            {
                ScriptIndex = Index(item.Script, "db/re/item_db.yml"),
                EquipScriptIndex = Index(item.EquipScript, "db/re/item_db.yml"),
                UnEquipScriptIndex = Index(item.UnEquipScript, "db/re/item_db.yml"),
            })
            .ToArray();

        return new(new ItemPack(commit, items, scripts), Report(items, scripts, loaded.Warnings.Count));
    }

    // Named accessors used by hand-written code and tests. The items themselves live in the data pack; this file only gives a
    // few well-known ones a typed name. Regenerated together with the pack so a renamed/removed item fails the build.
    internal static readonly (string Name, int Id, string Type)[] NamedItems =
    [
        ("Wood", 6008, "EtcItemDefinition"), ("Knife", 1201, "WeaponItemDefinition"), ("CottonShirt", 2301, "ArmorItemDefinition"),
        ("FirstAidBox", 23484, "UsableItemDefinition"), ("BluePotion", 11518, "HealingItemDefinition"), ("FreshMilk", 11614, "HealingItemDefinition"),
        ("NoviceMagnifier", 12325, "DelayConsumeItemDefinition"), ("CenterPotionB", 22542, "UsableItemDefinition"),
        ("FirstaidBox10", 23485, "UsableItemDefinition"), ("Magnifier", 611, "DelayConsumeItemDefinition"),
    ];

    internal static string RenderFacade(ItemPack pack, string commit)
    {
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated>")
            .AppendLine("// Generated by Athena.WorldCompiler (compile-item-pack).")
            .AppendLine($"// rAthena commit: {commit}")
            .AppendLine("// Do not edit this file directly.")
            .AppendLine("// </auto-generated>")
            .AppendLine("using Athena.Net.MapServer.World;")
            .AppendLine("using Athena.Net.MapServer.World.Items;")
            .AppendLine()
            .AppendLine("namespace Athena.Net.MapServer.Generated.GameData.Items;")
            .AppendLine()
            .AppendLine("// Typed names for a few well-known items plus the id lookup, all backed by the item data pack (ItemCatalog).")
            .AppendLine("internal static class GeneratedItems")
            .AppendLine("{")
            .AppendLine("    internal static System.Collections.Generic.IReadOnlyDictionary<int, ItemDefinition> ById => ItemCatalog.Current.ById;");
        foreach (var (name, id, type) in NamedItems)
        {
            var item = pack.Items.Single(candidate => candidate.Id == id);
            builder.AppendLine().AppendLine($"    // {item.AegisName}").AppendLine($"    internal static {type} {name} => ({type})ById[{id}];");
        }
        return builder.AppendLine("}").ToString();
    }

    private static string Report(IReadOnlyList<PackItem> items, IReadOnlyList<PackScript> scripts, int loaderWarnings)
    {
        var report = new StringBuilder();
        report.AppendLine($"items: {items.Count}");
        report.AppendLine($"loader warnings (pinned data quirks the real loader also reports): {loaderWarnings}");
        foreach (var group in items.GroupBy(item => item.Type).OrderBy(group => group.Key)) report.AppendLine($"  type {group.Key,2}: {group.Count()}");
        report.AppendLine($"distinct scripts: {scripts.Count}");
        report.AppendLine($"  lowered: {scripts.Count(script => script.Support == PackScriptSupport.Lowered)}");
        report.AppendLine($"  deferred: {scripts.Count(script => script.Support == PackScriptSupport.Deferred)}");
        foreach (var group in scripts.Where(script => script.Support == PackScriptSupport.Deferred)
                     .GroupBy(script => (script.DeferredOwner, Construct: script.DeferredConstruct!))
                     .OrderByDescending(group => group.Count()).ThenBy(group => group.Key.Construct, StringComparer.Ordinal))
            report.AppendLine($"    {group.Count(),6}  {group.Key.DeferredOwner,-14} {group.Key.Construct}");
        report.AppendLine("script uses (a script can use several):");
        foreach (var use in Enum.GetValues<PackScriptUses>().Where(use => use != PackScriptUses.None))
            report.AppendLine($"  {use,-16} {scripts.Count(script => script.Uses.HasFlag(use))}");
        return report.ToString();
    }
}
