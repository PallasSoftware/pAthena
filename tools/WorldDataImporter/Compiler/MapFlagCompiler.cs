using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Athena.WorldCompiler.Generation;

// Pinned npc_parse_mapflag (npc.cpp:5420+) and map_setmapflag_sub (map.cpp:4720-4892) for the flags item rules read:
// MF_NODROP (pc_dropitem), and the map types/zone itemdb_isNoEquip evaluates (PVP, GVG, GVG_TE, GVG_DUNGEON, GVG_CASTLE,
// GVG_TE_CASTLE, BATTLEGROUND, RESTRICTED <zone>). Directives are applied in load order (the active npc graph), with
// "off" and pinned's mutual exclusions, so a later line can clear an earlier one exactly as at server start.
// Flags scripts toggle at runtime (setmapflag, WoE agit_start) are not static data and are not represented here.
internal static partial class MapFlagCompiler
{
    [Flags]
    internal enum Flag : ushort
    {
        None = 0, Pvp = 1, Gvg = 2, GvgTe = 4, GvgDungeon = 8, GvgCastle = 16, GvgTeCastle = 32, Battleground = 64, NoDrop = 128, Restricted = 256,
    }

    private static readonly Dictionary<string, Flag> ByName = new(StringComparer.OrdinalIgnoreCase)
    {
        ["pvp"] = Flag.Pvp, ["gvg"] = Flag.Gvg, ["gvg_te"] = Flag.GvgTe, ["gvg_dungeon"] = Flag.GvgDungeon, ["gvg_castle"] = Flag.GvgCastle,
        ["gvg_te_castle"] = Flag.GvgTeCastle, ["battleground"] = Flag.Battleground, ["nodrop"] = Flag.NoDrop, ["restricted"] = Flag.Restricted,
    };

    internal sealed record MapState(Flag Flags, uint Zone);

    internal static SortedDictionary<string, MapState> Compile(IEnumerable<(string File, string Text)> activeFilesInLoadOrder)
    {
        var maps = new SortedDictionary<string, MapState>(StringComparer.Ordinal);
        foreach (var (_, text) in activeFilesInLoadOrder)
        foreach (var line in StripBlockComments(text).Split('\n'))
        {
            if (line.TrimStart().StartsWith("//", StringComparison.Ordinal)) continue;
            var columns = line.TrimEnd('\r').Split('\t', 4);
            if (columns.Length < 3 || columns[1] != "mapflag" || !ByName.TryGetValue(columns[2].Trim(), out var flag)) continue;
            var map = columns[0].Trim().Split(',')[0];
            var w4 = columns.Length > 3 ? columns[3].Trim() : "";
            var on = !w4.Equals("off", StringComparison.OrdinalIgnoreCase);
            var state = maps.GetValueOrDefault(map) ?? new MapState(Flag.None, 0);
            maps[map] = Apply(state, flag, on, w4);
        }
        foreach (var map in maps.Where(pair => pair.Value.Flags == Flag.None && pair.Value.Zone == 0).Select(pair => pair.Key).ToList()) maps.Remove(map);
        return maps;
    }

    private static MapState Apply(MapState state, Flag flag, bool on, string w4)
    {
        var flags = state.Flags;
        var zone = state.Zone;
        Flag Set(Flag f, bool value) => value ? flags | f : flags & ~f;
        switch (flag)
        {
            case Flag.Restricted:
                if (!on) return new(flags & ~Flag.Restricted, 0); // map_setmapflag(m, MF_RESTRICTED, false): args == nullptr -> zone = 0
                // sscanf("%11d") failing: pinned warns and skips the line.
                if (!int.TryParse(LeadingInteger(w4), NumberStyles.Integer, CultureInfo.InvariantCulture, out var value)) return state;
                return new(flags | Flag.Restricted, zone | (uint)((1 << (value + 1)) << 3));
            case Flag.Pvp:
                flags = Set(Flag.Pvp, on);
                if (on) flags &= ~(Flag.Gvg | Flag.GvgTe | Flag.GvgDungeon | Flag.GvgCastle | Flag.GvgTeCastle | Flag.Battleground);
                return new(flags, zone);
            case Flag.Gvg or Flag.GvgTe:
                flags = Set(flag, on);
                if (on) flags &= ~(Flag.Pvp | Flag.Battleground);
                return new(flags, zone);
            case Flag.GvgCastle or Flag.GvgTeCastle:
                if (on) flags &= ~((flag == Flag.GvgCastle ? Flag.GvgTeCastle : Flag.GvgCastle) | Flag.Pvp);
                return new(flags & ~flag | (on ? flag : Flag.None), zone);
            case Flag.GvgDungeon:
                if (on) flags &= ~Flag.Pvp;
                return new(flags & ~flag | (on ? flag : Flag.None), zone);
            default: // MF_NODROP, MF_BATTLEGROUND: plain set/clear
                return new(Set(flag, on), zone);
        }
    }

    private static string LeadingInteger(string text) => LeadingIntegerRegex().Match(text) is { Success: true } match ? match.Value : "";

    // npc_parsesrcfile skips /* */ comments wherever they appear (skip_space).
    private static string StripBlockComments(string text) => BlockCommentRegex().Replace(text.Replace("\r\n", "\n", StringComparison.Ordinal), match => new string('\n', match.Value.Count(c => c == '\n')));

    internal static string Emit(IReadOnlyDictionary<string, MapState> maps, string commit)
    {
        var output = new StringBuilder()
            .AppendLine("// <auto-generated>")
            .AppendLine("// Generated by Athena.WorldCompiler.")
            .AppendLine("// Source: mapflag directives of the active npc graph rooted at npc/re/scripts_main.conf")
            .Append("// rAthena commit: ").AppendLine(commit)
            .AppendLine("// Do not edit this file directly.")
            .AppendLine("// </auto-generated>")
            .AppendLine("using Athena.Net.MapServer.World;")
            .AppendLine()
            .AppendLine("namespace Athena.Net.MapServer.Generated.MapFlags;")
            .AppendLine()
            .AppendLine("internal static class GeneratedMapFlags")
            .AppendLine("{")
            .AppendLine("    internal static readonly IReadOnlyDictionary<string, MapFlagSet> ByMap = new Dictionary<string, MapFlagSet>(StringComparer.Ordinal)")
            .AppendLine("    {");
        foreach (var (map, state) in maps)
        {
            var names = Enum.GetValues<Flag>().Where(f => f != Flag.None && state.Flags.HasFlag(f)).Select(f => "MapFlag." + f).ToArray();
            output.Append("        [\"").Append(map).Append("\"] = new(").Append(names.Length == 0 ? "MapFlag.None" : string.Join(" | ", names))
                .Append(", 0x").Append(state.Zone.ToString("x", CultureInfo.InvariantCulture)).AppendLine("),");
        }
        return output.AppendLine("    };").AppendLine("}").ToString();
    }

    [GeneratedRegex(@"/\*.*?\*/", RegexOptions.Singleline)]
    private static partial Regex BlockCommentRegex();
    [GeneratedRegex(@"^[+-]?\d+")]
    private static partial Regex LeadingIntegerRegex();
}
